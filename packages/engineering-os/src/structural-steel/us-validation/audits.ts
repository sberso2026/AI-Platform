export function assertUsStandardGovernanceAudits(): void {
  if (!AISC_STEEL_FAMILY_REGISTERED || !US_STANDARD_VERSION_MODEL || !US_DESIGN_METHOD_MODEL) {
    throw new Error("AISC family/version/design-method model must remain registered");
  }
  if (SILENT_AISC_EDITION_INFERENCE || SILENT_STANDARD_IDENTITY_INFERENCE) {
    throw new Error("silent AISC standard identity inference is forbidden");
  }
  if (!BUILDING_CODE_AND_STEEL_STANDARD_SEPARATE || !US_JURISDICTION_AND_STANDARD_SEPARATE) {
    throw new Error("building-code and jurisdiction must remain separate from AISC identity");
  }
  if (US_CODE_PROFILE_INFERRED_FROM_USER_LOCATION) {
    throw new Error("US code profile must not be inferred from user location");
  }
  if (!AISC_NOT_HARDCODED_TO_US_GEOGRAPHY) {
    throw new Error("AISC must not be hardcoded to US geography");
  }
  if (SILENT_ASCE_EDITION_INFERENCE || SILENT_LOAD_STANDARD_EDITION_INFERENCE || !D1C_DEMAND_ENGINE_REUSED || PARALLEL_US_LOAD_COMBINATION_ENGINE) {
    throw new Error("load-standard dependency governance failed");
  }
  if (DEFAULT_LRFD_OR_ASD || SILENT_LRFD_ASD_CONVERSION || MIXED_LRFD_ASD_DESIGN_AUTHORITY_ALLOWED) {
    throw new Error("LRFD/ASD governance failed");
  }
  if (LOCAL_AMENDMENT_VALUE_GUESSED) throw new Error("local amendment values must not be guessed");
  if (STANDARD_UPDATE_OVERWRITES_HISTORICAL_RULE) {
    throw new Error("historical US standard context must remain reproducible");
  }
  if (DEFAULT_K_FACTOR || STABILITY_ANALYSIS_METHOD_MIXING_ALLOWED || US_MEMBER_STABILITY_METHOD_MIXING_ALLOWED || D1C_EQUALS_COMPLETE_US_STABILITY_ANALYSIS) {
    throw new Error("stability governance failed");
  }
}
