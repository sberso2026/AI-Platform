import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { EU_CONCRETE_PACK_CERTIFIED, EU_CONCRETE_PRODUCT_CLAIM_LEVEL, EU_CONCRETE_STANDARD_CONFORMANCE_STATE } from "@rtb/types";
import { D1E_INTERNAL_ROADMAP } from "./capability";
import {
  AI_BENCHMARK_TRUTH_AUTHORITY,
  AI_ENGINEER_VALIDATION_AUTHORITY,
  assertEuC10ReadinessPreservesLimits,
  C10_R1_CAN_SET_FORMAL_CONFORMANCE,
  C10_R1_CAN_SET_PACK_CERTIFIED,
  C10_READINESS_EQUALS_VALIDATION,
  EU_C10_CANONICAL_PHASE_SEQUENCE,
  EU_C10_DEFERRED_CAPABILITY_INVENTORY,
  EU_C10_ENGINEER_VALIDATED_METHOD_COUNT,
  EU_C10_ENGINEER_VALIDATED_ORCHESTRATOR_COUNT,
  EU_C10_IMPLEMENTED_CAPABILITY_INVENTORY,
  EU_C10_METHOD_BENCHMARK_REQUIREMENT_MATRIX,
  EU_C10_NEXT_PHASE,
  EU_C10_ORCHESTRATOR_BENCHMARK_REQUIREMENT_MATRIX,
  EU_C10_R2_CAN_GENERATE_EXPECTED_TRUTH_WITH_LLM,
  EU_C10_READY_WITH_LIMITATIONS_DEFINITION_RESULT,
  EU_C10_SINGLE_SOURCE_CAPABILITIES,
  EU_C10_UNSOURCED_IMPLEMENTED_RULE_COUNT,
  EU_C10_VALIDATION_LEDGER_PERSISTENCE_SCHEMA_CREATED,
  EU_C10_VALIDATION_QUEUE,
  FORMAL_STANDARD_CONFORMANCE_VALIDATED,
  LEVEL_0_ACCEPTABLE_AS_INDEPENDENT_VALIDATION,
  READY_WITH_LIMITATIONS_EQUALS_NEAR_CONFORMANCE,
  SCHEMA_CHANGE_REQUIRED,
} from "./eu-c10/readiness";

describe("EOS-D1E-EU-C10-R1 independent validation readiness", () => {
  it("defines evidence readiness without a new engineering method", () => {
    const source = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "eu-c10/readiness.ts"), "utf8");
    expect(source).not.toMatch(/\bMath\./);
    expect(source).not.toMatch(/\bfyd\b/);
    expect(source).not.toMatch(/evaluateEu/);
    expect(source).not.toMatch(/releaseEligible/);
    expect(EU_C10_IMPLEMENTED_CAPABILITY_INVENTORY).toHaveLength(16);
    expect(EU_C10_DEFERRED_CAPABILITY_INVENTORY).toHaveLength(23);
    expect(EU_C10_VALIDATION_QUEUE).toEqual(EU_C10_IMPLEMENTED_CAPABILITY_INVENTORY);
    expect(EU_C10_SINGLE_SOURCE_CAPABILITIES).toEqual([
      "C7_CRACK_WIDTH",
      "C7_EXPLICIT_LONG_TERM_STATE",
      "C8_COVER_ASSEMBLY",
      "C8_MINIMUM_CLEAR_SPACING",
      "C8_BASIC_REQUIRED_ANCHORAGE",
    ]);
    expect(EU_C10_UNSOURCED_IMPLEMENTED_RULE_COUNT).toBe(0);
    expect(EU_C10_METHOD_BENCHMARK_REQUIREMENT_MATRIX).toHaveLength(12);
    expect(EU_C10_ORCHESTRATOR_BENCHMARK_REQUIREMENT_MATRIX).toHaveLength(4);
    expect(EU_C10_ORCHESTRATOR_BENCHMARK_REQUIREMENT_MATRIX.every((row) => row.equivalenceProvesFormulaTruth === false)).toBe(true);
    expect(EU_C10_READY_WITH_LIMITATIONS_DEFINITION_RESULT).toBe("PASS");
    expect(READY_WITH_LIMITATIONS_EQUALS_NEAR_CONFORMANCE).toBe(false);
    expect(C10_READINESS_EQUALS_VALIDATION).toBe(false);
    expect(LEVEL_0_ACCEPTABLE_AS_INDEPENDENT_VALIDATION).toBe(false);
    expect(EU_C10_R2_CAN_GENERATE_EXPECTED_TRUTH_WITH_LLM).toBe(false);
    expect(AI_ENGINEER_VALIDATION_AUTHORITY).toBe(false);
    expect(AI_BENCHMARK_TRUTH_AUTHORITY).toBe(false);
    expect(EU_C10_ENGINEER_VALIDATED_METHOD_COUNT).toBe(0);
    expect(EU_C10_ENGINEER_VALIDATED_ORCHESTRATOR_COUNT).toBe(0);
    expect(FORMAL_STANDARD_CONFORMANCE_VALIDATED).toBe(false);
    expect(C10_R1_CAN_SET_FORMAL_CONFORMANCE).toBe(false);
    expect(C10_R1_CAN_SET_PACK_CERTIFIED).toBe(false);
    expect(EU_CONCRETE_PACK_CERTIFIED).toBe(false);
    expect(EU_CONCRETE_STANDARD_CONFORMANCE_STATE).toBe("INTENDED_PROFILE");
    expect(EU_CONCRETE_PRODUCT_CLAIM_LEVEL).toBe("EU_CONCRETE_MECHANICS_REFERENCE_CAPABILITY");
    expect(SCHEMA_CHANGE_REQUIRED).toBe(false);
    expect(EU_C10_VALIDATION_LEDGER_PERSISTENCE_SCHEMA_CREATED).toBe(false);
    expect(EU_C10_CANONICAL_PHASE_SEQUENCE[0]).toBe("EOS-D1E-EU-C10-R1-INDEPENDENT-VALIDATION-READINESS");
    expect(EU_C10_NEXT_PHASE).toBe("EOS-D1E-EU-C10-R2-METHOD-MEMBER-BENCHMARKS");
    expect(D1E_INTERNAL_ROADMAP.find((row) => row.id === "EOS-D1E-EU-C10-R1-INDEPENDENT-VALIDATION-READINESS")?.status).toBe("CLOSED");
    expect(D1E_INTERNAL_ROADMAP.find((row) => row.id === "EOS-D1E-EU-C10-FINAL-CONFORMANCE-RELEASE-DECISION")?.status).toBe("NOT_STARTED");
    expect(() => assertEuC10ReadinessPreservesLimits()).not.toThrow();
  });
});
