export function assertEuC7CloseoutPreservesPriorFlags(): void {
  if (NEW_C7_DEFLECTION_RUNTIME_METHOD_IMPLEMENTED) throw new Error("deflection runtime must stay absent");
  if (NEW_C7_CREEP_RUNTIME_METHOD_IMPLEMENTED || NEW_C7_SHRINKAGE_RUNTIME_METHOD_IMPLEMENTED) {
    throw new Error("calculated creep and shrinkage models must stay absent");
  }
  if (EU_C7_R3_CALCULATED_CREEP_IMPLEMENTED || EU_C7_R3_CALCULATED_SHRINKAGE_IMPLEMENTED) {
    throw new Error("calculated long-term models must stay absent");
  }
  if (EU_C7_R3_ENVIRONMENTAL_CREEP_MODEL_IMPLEMENTED || EU_C7_R3_ENVIRONMENTAL_SHRINKAGE_MODEL_IMPLEMENTED) {
    throw new Error("environmental long-term models must stay absent");
  }
  if (EU_C7_R3_CREEP_DEFAULTED || EU_C7_R3_SHRINKAGE_DEFAULTED || C7_LONG_TERM_VALUE_DEFAULTS_PRESENT) {
    throw new Error("long-term values must not default");
  }
  if (EU_C7_ENGINEER_VALIDATED_METHOD_COUNT !== EU_C7_R2_ENGINEER_VALIDATED_METHOD_COUNT + EU_C7_R3_ENGINEER_VALIDATED_LONG_TERM_METHOD_COUNT) {
    throw new Error("engineer-validated count drifted");
  }
  if (!C6_EXISTING_EXPLICIT_PHIEF_PATH_PRESERVED || C7_AUTOMATICALLY_REPLACES_C6_PHIEF || C7_PHI_EQUALS_C6_PHIEF_AUTOMATICALLY) {
    throw new Error("C6 phiEf path must stay explicit and separate");
  }
  if (C7_PHI_TO_PHIEF_TRANSFORMATION_IMPLEMENTED) throw new Error("phi-to-phiEf transformation must stay absent");
  if (!C7_SIGMA_S_REMAINS_GOVERNED_SLS_INPUT || ULS_STEEL_STRESS_USED_AS_C7_SLS_INPUT) {
    throw new Error("crack steel stress must stay an explicit SLS input");
  }
  if (EU_C7_DEFLECTION_RUNTIME_CAPABILITY !== "NOT_IMPLEMENTED") throw new Error("deflection runtime must stay unimplemented");
  if (EU_C7_CLOSEOUT_RUNTIME_METHOD_IDS.some((methodId) => methodId.toLowerCase().includes("deflection"))) {
    throw new Error("deflection must not be registered as a runtime method");
  }
  if (EU_C7_R2_METHOD_REGISTRY.length !== 1 || EU_C7_R3_METHOD_REGISTRY.length !== 1) {
    throw new Error("C7 runtime registries must stay at the bounded crack and long-term methods");
  }
  if (NEW_C7_CRACK_WIDTH_RUNTIME_METHOD_IMPLEMENTED) {
    throw new Error("R1 crack-width absent flag must stay false; R2 owns the implemented method");
  }
}
