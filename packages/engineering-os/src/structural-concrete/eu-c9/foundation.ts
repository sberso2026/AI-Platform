export function assertEuC9FoundationPreservesPriorLimits(): void {
  if (EU_C9_ORCHESTRATION_CAN_INVENT_MISSING_METHODS) throw new Error("orchestration must not invent methods");
  if (!CONCRETE_ELEMENT_TYPES.includes("BEAM") || !CONCRETE_ELEMENT_TYPES.includes("COLUMN") || !CONCRETE_ELEMENT_TYPES.includes("SLAB") || !CONCRETE_ELEMENT_TYPES.includes("WALL")) {
    throw new Error("canonical member types drifted");
  }
  if (EU_C6_R2_AXIAL_SIGN_CONVERSION_COUNT !== 1 || EU_C9_C6_C3_DOUBLE_SIGN_CONVERSION) {
    throw new Error("C6 to C3 sign conversion must occur once");
  }
  if (DEFLECTION_RUNTIME_CAPABILITY !== "NOT_IMPLEMENTED" || EU_C9_EXPLICIT_LONG_TERM_STATE_EQUALS_DEFLECTION_CAPABILITY) {
    throw new Error("deflection must stay unimplemented");
  }
  if (euC9ExecutionDagHasCycle() || !EU_C9_EXECUTION_DAG_ACYCLIC) throw new Error("execution graph must stay acyclic");
  if (aggregateEuC9MemberChecks(["SATISFIED", "DEFERRED"]) === "MEMBER_SATISFIED_FOR_EXECUTED_BOUNDED_SCOPE") {
    throw new Error("a deferred check must not aggregate to pass");
  }
  if (EU_C9_R1_RUNTIME_MEMBER_ORCHESTRATOR_COUNT !== 0) throw new Error("R1 must not run a member orchestrator");
}
