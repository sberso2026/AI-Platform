export function euC9ExecutionDagHasCycle(): boolean {
  const upstream = new Map<string, readonly string[]>(EU_C9_EXECUTION_DAG.map((node) => [node.id, node.upstream]));
  const visiting = new Set<string>();
  const visited = new Set<string>();
  const walk = (id: string): boolean => {
    if (visiting.has(id)) return true;
    if (visited.has(id)) return false;
    visiting.add(id);
    for (const parent of upstream.get(id) ?? []) {
      if (walk(parent)) return true;
    }
    visiting.delete(id);
    visited.add(id);
    return false;
  };
  return EU_C9_EXECUTION_DAG.some((node) => walk(node.id));
}

