import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { EU_CONCRETE_PACK_CERTIFIED, EU_CONCRETE_PRODUCT_CLAIM_LEVEL, EU_CONCRETE_STANDARD_CONFORMANCE_STATE } from "@rtb/types";
import { CONCRETE_CAPABILITY_MANIFEST, D1E_INTERNAL_ROADMAP } from "./capability";
import { DEFLECTION_RUNTIME_CAPABILITY } from "./eu-c7/deflection-authority";
import {
  AI_C9_ASSISTANCE_ADVISORY_ONLY,
  AI_ENGINEERING_APPROVAL,
  C10_READINESS_EQUALS_CONFORMANCE,
  C8_DEFERRED_DEBT_PRESERVED,
  C9_ORCHESTRATION_EQUALS_STANDARD_CONFORMANCE,
  EU_C10_ENGINEER_VALIDATION_GAP_PRESENT,
  EU_C10_EXPLICIT_NATIONAL_PROFILE_VALIDATION_GAP_PRESENT,
  EU_C10_PROPOSED_PHASE_SEQUENCE,
  EU_C10_STARTS_CERTIFIED,
  EU_C10_STARTS_CONFORMANCE_VALIDATED,
  EU_C9_BEAM_CAPABILITY_CLASS,
  EU_C9_BOUNDED_TRACK_COMPLETE,
  EU_C9_COLUMN_BIAXIAL_SECOND_ORDER_AVAILABLE,
  EU_C9_COMPLETE_EN1992_MEMBER_DESIGN,
  EU_C9_DOCUMENTATION_INVENTORY,
  EU_C9_ENGINEER_VALIDATED_MEMBER_ORCHESTRATOR_COUNT,
  EU_C9_ENGINEER_VALIDATION_STATE,
  EU_C9_FULL_STANDARD_COVERAGE_FOR_ANY_MEMBER,
  EU_C9_IMPLEMENTED_MEMBER_ORCHESTRATOR_COUNT,
  EU_C9_MATURITY_STATE,
  EU_C9_MEMBER_SPECIFIC_VALIDATION_DEBT,
  EU_C9_NEXT_ROADMAP_PHASE,
  EU_C9_NUMERICALLY_VALIDATED_MEMBER_ORCHESTRATOR_COUNT,
  EU_C9_ORCHESTRATOR_REGISTRY_COUNT,
  EU_C9_RELEASE_CLASSIFICATION_CORRECTIONS,
  EU_C9_VALIDATION_MATRIX,
  EU_C9_WALL_CAPABILITY_CLASS,
  EU_C9_WALL_IDENTITY_CONFLICT,
  EU_C9_WALL_MEMBER_DESIGN_AVAILABLE,
  NEW_C9_ENGINEERING_FORMULA_IMPLEMENTED,
  NEW_C9_RUNTIME_MEMBER_ORCHESTRATOR_IMPLEMENTED,
  assertEuC9CloseoutPreservesPriorLimits,
} from "./eu-c9/closeout";
import { EU_C9_ORCHESTRATOR_REGISTRY } from "./eu-c9/wall";

describe("EOS-D1E-EU-C9-R6 closeout", () => {
  it("closes the bounded track without a new method", () => {
    const source = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "eu-c9/closeout.ts"), "utf8");
    expect(source.includes("Math.")).toBe(false);
    expect(source.includes("fyd")).toBe(false);
    expect(source.includes("evaluateEu")).toBe(false);
    expect(NEW_C9_ENGINEERING_FORMULA_IMPLEMENTED).toBe(false);
    expect(NEW_C9_RUNTIME_MEMBER_ORCHESTRATOR_IMPLEMENTED).toBe(false);
    expect(EU_C9_BOUNDED_TRACK_COMPLETE).toBe(true);
    expect(EU_C9_COMPLETE_EN1992_MEMBER_DESIGN).toBe(false);
    expect(EU_C9_MATURITY_STATE).toBe("FRAMEWORK_PLUS_BOUNDED_MEMBER_ORCHESTRATORS");
    expect(EU_C9_IMPLEMENTED_MEMBER_ORCHESTRATOR_COUNT).toBe(4);
    expect(EU_C9_NUMERICALLY_VALIDATED_MEMBER_ORCHESTRATOR_COUNT).toBe(4);
    expect(EU_C9_ENGINEER_VALIDATED_MEMBER_ORCHESTRATOR_COUNT).toBe(0);
    expect(EU_C9_ORCHESTRATOR_REGISTRY.map((row) => row.orchestratorId)).toHaveLength(EU_C9_ORCHESTRATOR_REGISTRY_COUNT);
    expect(EU_C9_WALL_IDENTITY_CONFLICT).toBe(false);
    expect(EU_C9_BEAM_CAPABILITY_CLASS).toBe("BOUNDED_MEMBER_ORCHESTRATION");
    expect(EU_C9_WALL_CAPABILITY_CLASS).toBe("BOUNDED_SECTION_ORCHESTRATION");
    expect(EU_C9_WALL_MEMBER_DESIGN_AVAILABLE).toBe(false);
    expect(EU_C9_COLUMN_BIAXIAL_SECOND_ORDER_AVAILABLE).toBe(false);
    expect(EU_C9_FULL_STANDARD_COVERAGE_FOR_ANY_MEMBER).toBe(false);
    expect(EU_C9_VALIDATION_MATRIX.WALL_SECTION.orchestrationClass).toBe("BOUNDED_SECTION_ORCHESTRATION");
    expect(EU_C9_VALIDATION_MATRIX.BEAM.engineerValidated).toBe(false);
    expect(EU_C9_MEMBER_SPECIFIC_VALIDATION_DEBT.WALL).toContain("WALL_STABILITY");
    expect(EU_C9_MEMBER_SPECIFIC_VALIDATION_DEBT.SLAB).toContain("TWO_WAY_SLAB_ANALYSIS");
    expect(C8_DEFERRED_DEBT_PRESERVED).toBe(true);
    expect(EU_C9_ENGINEER_VALIDATION_STATE).toBe("PENDING_HUMAN_ENGINEERING_REVIEW");
    expect(EU_C10_STARTS_CERTIFIED).toBe(false);
    expect(EU_C10_STARTS_CONFORMANCE_VALIDATED).toBe(false);
    expect(EU_C10_ENGINEER_VALIDATION_GAP_PRESENT).toBe(true);
    expect(EU_C10_EXPLICIT_NATIONAL_PROFILE_VALIDATION_GAP_PRESENT).toBe(true);
    expect(C10_READINESS_EQUALS_CONFORMANCE).toBe(false);
    expect(EU_C10_PROPOSED_PHASE_SEQUENCE[0]).toBe("EOS-D1E-EU-C10-R1-INDEPENDENT-VALIDATION-READINESS");
    expect(EU_C9_NEXT_ROADMAP_PHASE).toBe("EOS-D1E-EU-C10-R1-INDEPENDENT-VALIDATION-READINESS");
    expect(EU_C9_RELEASE_CLASSIFICATION_CORRECTIONS).toEqual(["NONE"]);
    expect(EU_C9_DOCUMENTATION_INVENTORY).toHaveLength(6);
    expect(AI_C9_ASSISTANCE_ADVISORY_ONLY).toBe(true);
    expect(AI_ENGINEERING_APPROVAL).toBe(false);
    expect(C9_ORCHESTRATION_EQUALS_STANDARD_CONFORMANCE).toBe(false);
    expect(() => assertEuC9CloseoutPreservesPriorLimits()).not.toThrow();
    expect(DEFLECTION_RUNTIME_CAPABILITY).toBe("NOT_IMPLEMENTED");
    expect(EU_CONCRETE_PRODUCT_CLAIM_LEVEL).toBe("EU_CONCRETE_MECHANICS_REFERENCE_CAPABILITY");
    expect(EU_CONCRETE_PACK_CERTIFIED).toBe(false);
    expect(EU_CONCRETE_STANDARD_CONFORMANCE_STATE).toBe("INTENDED_PROFILE");
  });

  it("keeps the manifest and roadmap truthful", () => {
    const row = (id: string) => CONCRETE_CAPABILITY_MANIFEST.find((item) => item.capabilityId === id);
    expect(row("D1E.EU.C9.BEAM_ORCHESTRATION")?.implementationState).toBe("IMPLEMENTED_NUMERICALLY_VALIDATED");
    expect(row("D1E.EU.C9.COLUMN_ORCHESTRATION")?.implementationState).toBe("IMPLEMENTED_NUMERICALLY_VALIDATED");
    expect(row("D1E.EU.C9.SOLID_SLAB_ORCHESTRATION")?.implementationState).toBe("IMPLEMENTED_NUMERICALLY_VALIDATED");
    expect(row("D1E.EU.C9.WALL_SECTION_ORCHESTRATION")?.implementationState).toBe("IMPLEMENTED_NUMERICALLY_VALIDATED");
    expect(row("D1E.EU.C9.WALL_SECTION_ORCHESTRATION")?.limitations).toContain("section check is not wall-member design");
    expect(row("D1E.EU.C8.LAPS")?.implementationState).toBe("DEFERRED_RULE_AUTHORITY");
    expect(row("D1E.EU.C8.DESIGN_ANCHORAGE")?.implementationState).toBe("NOT_IMPLEMENTED");
    expect(D1E_INTERNAL_ROADMAP.find((item) => item.id === "EOS-D1E-EU-C9-R6-CLOSEOUT")?.status).toBe("CLOSED");
    expect(D1E_INTERNAL_ROADMAP.find((item) => item.id === "EOS-D1E-EU-C10-R1-INDEPENDENT-VALIDATION-READINESS")?.status).toBe("NOT_STARTED");
  });
});
