import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  D1_CANONICAL_NEXT_PHASE,
  D1_CANONICAL_PHASE_LIST,
  D1_CANONICAL_TOTAL_MILESTONE_COUNT,
  D1_COMPLETED_MILESTONE_COUNT,
  D1_REMAINING_MILESTONE_COUNT,
} from "./d1-structural-debt-canonicalization";
import { scanAnalysisFormulaBypass } from "./formula-scan";
import { D1G_VALIDATION_ROUTE_PHASE } from "./roadmap-after-twin-closeout";
import { D1_STRUCTURAL_PACK_COMPLETE, D1G_VALIDATION_ROUTE_COMPLETED } from "./structural-pack-sequencing";
import {
  ADMIN_EQUALS_STRUCTURAL_ENGINEERING_AUTHORITY,
  AI_EQUALS_STRUCTURAL_ENGINEERING_AUTHORITY,
  D1_CANONICAL_NEXT_PHASE as LIVE_NEXT_PHASE,
  D1_CANONICAL_NEXT_PHASE_TYPE,
  D1_CANONICAL_PHASE_LIST as LIVE_PHASE_LIST,
  D1_CANONICAL_TOTAL_MILESTONE_COUNT as LIVE_TOTAL,
  D1_COMPLETED_MILESTONE_COUNT as LIVE_COMPLETED,
  D1_REMAINING_MILESTONE_COUNT as LIVE_REMAINING,
  D1G_ANALYTICAL_BENCHMARK_EXECUTED,
  D1G_ANALYTICAL_BENCHMARK_ROUTE_DEFINED,
  D1G_APPLICABILITY_REQUIRED,
  D1G_CAN_SILENTLY_DROP_LIMITATIONS,
  D1G_CONFORMANCE_VALIDATION_ROUTE_DEFINED,
  D1G_CONFORMANCE_VALIDATION_SATISFIED,
  D1G_DEFAULT_TOLERANCE_CREATED,
  D1G_ENGINEER_VALIDATION_ROUTE_DEFINED,
  D1G_ENGINEER_VALIDATION_SATISFIED,
  D1G_EXECUTION_STATUS,
  D1G_HISTORICAL_REFERENCE_AUTO_REPOINTED,
  D1G_INDEPENDENT_REFERENCE_COMPARISON_ACCEPTED_FORMS,
  D1G_LIMITATIONS_REQUIRED,
  D1G_LIVE_VALIDATION_EXECUTED,
  D1G_LIVE_VALIDATION_ROUTE_DEFINED,
  D1G_OPTIONAL_EVIDENCE_CLASSES,
  D1G_PROVIDER_BOUNDARY_DEFINED,
  D1G_REFERENCE_COMPARISON_ROUTE_DEFINED,
  D1G_REQUIRED_EVIDENCE_CLASSES,
  D1G_ROUTE_STATUS,
  D1G_SELF_REFERENCE_EQUALS_INDEPENDENT_VALIDATION,
  D1G_TOLERANCE_JUSTIFICATION_REQUIRED,
  D1G_TOLERANCE_REQUIRED,
  D1G_VALIDATION_EVIDENCE_CLASSES,
  D1G_VALIDATION_EXACT_REVISION_REQUIRED,
  D1G_VALIDATION_FLOATING_REFERENCE_ALLOWED,
  D1G_VALIDATION_RECORD_SEMANTICS_DEFINED,
  D1G_VALIDATION_ROUTE_DEFINED,
  D1G_VALIDATION_ROUTE_EXECUTED,
  D1G_VALIDATION_SCOPE_MATRIX,
  DATABASE_SCHEMA_CHANGED,
  IMPLEMENTATION_MATCHES_DOCUMENTED_METHOD_EQUALS_ENGINEERING_CONFORMANT,
  NEW_DEPENDENCY_ADDED,
  NEW_D1G_REVISION_INHERITS_CONFORMANCE,
  NEW_D1G_REVISION_INHERITS_ENGINEER_REVIEW,
  NEW_D1G_REVISION_INHERITS_VALIDATION,
  NEW_SUBSTANTIVE_RUNTIME_COUNT,
  STANDARD_SELECTED_EQUALS_ENGINEERING_CONFORMANT,
  VALIDATION_PASS_EQUALS_ENGINEERING_CONFORMANT,
  verifyD1gValidationRoute,
} from "./d1g-validation-route-canonicalization";

const here = dirname(fileURLToPath(import.meta.url));

describe("EOS-D1G validation route canonicalization", () => {
  it("keeps the 15-phase roadmap and advances only the route definition", () => {
    expect(verifyD1gValidationRoute()).toEqual({ completed: 8, remaining: 7, total: 15 });
    expect(D1_CANONICAL_TOTAL_MILESTONE_COUNT).toBe(15);
    expect(D1_COMPLETED_MILESTONE_COUNT).toBe(7);
    expect(D1_REMAINING_MILESTONE_COUNT).toBe(8);
    expect(D1_CANONICAL_NEXT_PHASE).toBe("EOS-D1G-VALIDATION-ROUTE-CANONICALIZATION");
    expect(LIVE_TOTAL).toBe(15);
    expect(LIVE_COMPLETED).toBe(8);
    expect(LIVE_REMAINING).toBe(7);
    expect(LIVE_PHASE_LIST).toEqual(D1_CANONICAL_PHASE_LIST);
    expect(D1G_ROUTE_STATUS).toBe("COMPLETE");
    expect(D1G_VALIDATION_ROUTE_DEFINED).toBe(true);
    expect(D1G_VALIDATION_ROUTE_EXECUTED).toBe(false);
    expect(D1G_VALIDATION_ROUTE_PHASE).toBe("NOT_DEFINED");
    expect(D1G_VALIDATION_ROUTE_COMPLETED).toBe(false);
    expect(D1_STRUCTURAL_PACK_COMPLETE).toBe(false);
    expect(LIVE_NEXT_PHASE).toBe("EOS-D1-QUALIFIED-STRUCTURAL-REVIEW");
    expect(D1_CANONICAL_NEXT_PHASE_TYPE).toBe("QUALIFIED_STRUCTURAL_REVIEW");
    expect(NEW_SUBSTANTIVE_RUNTIME_COUNT).toBe(0);
    expect(DATABASE_SCHEMA_CHANGED || NEW_DEPENDENCY_ADDED).toBe(false);
  });

  it("defines evidence, provider, tolerance, applicability, and revision boundaries without execution", () => {
    expect(D1G_VALIDATION_EVIDENCE_CLASSES).toContain("CLOSED_FORM_ANALYTICAL_BENCHMARK");
    expect(D1G_REQUIRED_EVIDENCE_CLASSES).toContain("INDEPENDENT_REFERENCE_COMPARISON");
    expect(D1G_REQUIRED_EVIDENCE_CLASSES).toContain("QUALIFIED_STRUCTURAL_ENGINEER_REVIEW");
    expect(D1G_OPTIONAL_EVIDENCE_CLASSES).toContain("LIVE_PROVIDER_SESSION");
    expect(D1G_OPTIONAL_EVIDENCE_CLASSES).not.toContain("INDEPENDENT_REFERENCE_COMPARISON");
    expect(D1G_INDEPENDENT_REFERENCE_COMPARISON_ACCEPTED_FORMS).toEqual([
      "CLOSED_FORM_ANALYTICAL_BENCHMARK",
      "INDEPENDENT_CALCULATION",
      "THIRD_PARTY_REFERENCE_OUTPUT",
    ]);
    expect(D1G_ANALYTICAL_BENCHMARK_ROUTE_DEFINED).toBe(true);
    expect(D1G_ANALYTICAL_BENCHMARK_EXECUTED).toBe(false);
    expect(D1G_REFERENCE_COMPARISON_ROUTE_DEFINED).toBe(true);
    expect(D1G_PROVIDER_BOUNDARY_DEFINED).toBe(true);
    expect(D1G_SELF_REFERENCE_EQUALS_INDEPENDENT_VALIDATION).toBe(false);
    expect(D1G_TOLERANCE_REQUIRED && D1G_TOLERANCE_JUSTIFICATION_REQUIRED).toBe(true);
    expect(D1G_DEFAULT_TOLERANCE_CREATED).toBe(false);
    expect(D1G_APPLICABILITY_REQUIRED && D1G_LIMITATIONS_REQUIRED).toBe(true);
    expect(D1G_CAN_SILENTLY_DROP_LIMITATIONS).toBe(false);
    expect(D1G_VALIDATION_SCOPE_MATRIX.every((row) => row.executionStatus === "NOT_EXECUTED")).toBe(true);
    expect(D1G_LIVE_VALIDATION_ROUTE_DEFINED).toBe(true);
    expect(D1G_LIVE_VALIDATION_EXECUTED).toBe(false);
    expect(D1G_ENGINEER_VALIDATION_ROUTE_DEFINED).toBe(true);
    expect(D1G_ENGINEER_VALIDATION_SATISFIED).toBe(false);
    expect(D1G_CONFORMANCE_VALIDATION_ROUTE_DEFINED).toBe(true);
    expect(D1G_CONFORMANCE_VALIDATION_SATISFIED).toBe(false);
    expect(IMPLEMENTATION_MATCHES_DOCUMENTED_METHOD_EQUALS_ENGINEERING_CONFORMANT).toBe(false);
    expect(STANDARD_SELECTED_EQUALS_ENGINEERING_CONFORMANT).toBe(false);
    expect(VALIDATION_PASS_EQUALS_ENGINEERING_CONFORMANT).toBe(false);
    expect(D1G_VALIDATION_RECORD_SEMANTICS_DEFINED).toBe(true);
    expect(D1G_VALIDATION_EXACT_REVISION_REQUIRED).toBe(true);
    expect(D1G_VALIDATION_FLOATING_REFERENCE_ALLOWED).toBe(false);
    expect(D1G_HISTORICAL_REFERENCE_AUTO_REPOINTED).toBe(false);
    expect(NEW_D1G_REVISION_INHERITS_VALIDATION || NEW_D1G_REVISION_INHERITS_ENGINEER_REVIEW || NEW_D1G_REVISION_INHERITS_CONFORMANCE).toBe(false);
    expect(AI_EQUALS_STRUCTURAL_ENGINEERING_AUTHORITY || ADMIN_EQUALS_STRUCTURAL_ENGINEERING_AUTHORITY).toBe(false);
    expect(D1G_EXECUTION_STATUS).toBe("NOT_EXECUTED");
    const sourceText = readFileSync(join(here, "d1g-validation-route-canonicalization.ts"), "utf8");
    expect(sourceText).not.toMatch(/createHash|from ["']@rtb\/engineering-review["']|CREATE TABLE|eval\(|child_process|new Function/);
    expect(scanAnalysisFormulaBypass(join(here, "d1g-validation-route-canonicalization.ts"), sourceText)).toEqual([]);
  });
});
