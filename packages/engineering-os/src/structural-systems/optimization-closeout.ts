export type D1jClaimScope = (typeof D1J_R5_CLAIM_SCOPES)[number];

export function claimScopeSupported(claim: D1jClaimScope, input: { comparisonIneligible: boolean; feasibilityState: string; eligibilityState: string }): boolean {
  if (claim === "CERTIFICATION_ELIGIBILITY_CLAIM") return input.eligibilityState === "ELIGIBLE";
  if (claim === "MULTI_OBJECTIVE_COMPARISON_CLAIM" || claim === "PARETO_COMPOSITION_CLAIM") return input.comparisonIneligible === false;
  if (claim === "FEASIBILITY_CLAIM") return input.feasibilityState === "FEASIBLE" || input.feasibilityState === "INFEASIBLE" || input.feasibilityState === "UNDETERMINED";
  return claim === "CANDIDATE_EVIDENCE_CLAIM" || claim === "SELECTED_ALTERNATIVE_CLAIM";
}
