import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { D9_STATUS, D9_TRACK_COMPLETE } from "../cross-discipline/cross-discipline-bounded-closeout";
import { scanAnalysisFormulaBypass } from "./formula-scan";
import {
  D1_ANALYTICAL_BENCHMARK_STATUS,
  D1_BLOCKED_DEBT_ITEM_COUNT,
  D1_BLOCKED_DEBT_ITEMS,
  D1_CANONICAL_NEXT_PHASE,
  D1_CANONICAL_NEXT_PHASE_SCOPE,
  D1_CANONICAL_NEXT_PHASE_TYPE,
  D1_CANONICAL_PHASE_LIST,
  D1_CANONICAL_TOTAL_MILESTONE_COUNT,
  D1_CLOSEOUT_CRITERIA,
  D1_CLOSEOUT_TARGET,
  D1_COMPLETE_DEBT_ITEM_COUNT,
  D1_COMPLETE_WITH_LIMITATIONS_COUNT,
  D1_COMPLETED_MILESTONE_COUNT,
  D1_CURRENT_MATURITY,
  D1_DEBT_ITEM_COUNT,
  D1_DEBT_ITEMS,
  D1_HISTORICAL_PHASE_COUNT,
  D1_HISTORICAL_PHASE_LIST,
  D1_INCOMPLETE_DEBT_ITEM_COUNT,
  D1_INTERNAL_INTEGRATION_STATUS,
  D1_METHOD_CONFORMANCE_STATUS,
  D1_NOT_REQUIRED_DEBT_ITEM_COUNT,
  D1_PARAMETER_SEMANTICS_STATUS,
  D1_QUALIFIED_HUMAN_REVIEW_STATUS,
  D1_READY_FOR_NEXT_PHASE,
  D1_REFERENCE_SOLVER_COMPARISON_STATUS,
  D1_REMAINING_MILESTONE_COUNT,
  D1_REMAINING_PHASES,
  D1_REQUIRED_EXTERNAL_EVIDENCE_COUNT,
  D1_REQUIRED_MANUAL_HUMAN_ACTION_COUNT,
  D1_SOLVER_VALIDATION_STATUS,
  D1_STANDARDS_JURISDICTION_STATUS,
  D1_STRUCTURAL_ENGINEER_REVIEW_WORKFLOW_STATUS,
  D1_SUPERSEDED_DEBT_ITEM_COUNT,
  D1_TO_D9_SOURCE_CONTRACT_STATUS,
  D1_UNSUPPORTED_CLAIM_DEBT_STATUS,
  D1_VALIDATION_EVIDENCE_MATRIX_STATUS,
  D1K_REOPEN_REQUIRED,
  D1K_STATUS,
  D1L_REOPEN_REQUIRED,
  D1L_STATUS,
  D1N_REOPEN_REQUIRED,
  D1N_STATUS,
  D9_REOPENED,
  DATABASE_SCHEMA_CHANGED,
  EOS_ALL_DISCIPLINES_COMPLETE,
  EOS_GA_READY,
  EOS_PRODUCT_SECURITY_RELEASE_DEBT_COUNT,
  NEW_DEPENDENCY_ADDED,
  NEW_SUBSTANTIVE_RUNTIME_COUNT,
  STRUCTURAL_ENGINEERING_DEBT_COUNT,
  verifyD1DebtCanonicalization,
} from "./d1-structural-debt-canonicalization";
import { D1_STRUCTURAL_PACK_COMPLETE } from "./structural-pack-sequencing";

const here = dirname(fileURLToPath(import.meta.url));

describe("EOS D1 structural debt canonicalization", () => {
  it("keeps the pack incomplete and names one next phase from the undefined D1G route", () => {
    expect(verifyD1DebtCanonicalization()).toEqual({ total: 15, completed: 7, remaining: 8, debtItems: D1_DEBT_ITEM_COUNT });
    expect(D1_STRUCTURAL_PACK_COMPLETE).toBe(false);
    expect(D1_CURRENT_MATURITY).toBe("STRUCTURAL_PACK_INCOMPLETE");
    expect(NEW_SUBSTANTIVE_RUNTIME_COUNT).toBe(0);
    expect(D1_HISTORICAL_PHASE_COUNT).toBe(D1_HISTORICAL_PHASE_LIST.length);
    expect(D1_COMPLETED_MILESTONE_COUNT).toBe(7);
    expect(D1_REMAINING_MILESTONE_COUNT).toBe(8);
    expect(D1_CANONICAL_TOTAL_MILESTONE_COUNT).toBe(15);
    expect(D1_CANONICAL_PHASE_LIST).toHaveLength(15);
    expect(D1_DEBT_ITEM_COUNT).toBe(D1_DEBT_ITEMS.length);
    expect(D1_COMPLETE_DEBT_ITEM_COUNT).toBe(0);
    expect(D1_COMPLETE_WITH_LIMITATIONS_COUNT).toBeGreaterThan(0);
    expect(D1_INCOMPLETE_DEBT_ITEM_COUNT).toBeGreaterThan(0);
    expect(D1_BLOCKED_DEBT_ITEM_COUNT).toBe(D1_BLOCKED_DEBT_ITEMS.length);
    expect(D1_SUPERSEDED_DEBT_ITEM_COUNT).toBeGreaterThan(0);
    expect(D1_NOT_REQUIRED_DEBT_ITEM_COUNT).toBeGreaterThan(0);
    expect(STRUCTURAL_ENGINEERING_DEBT_COUNT).toBe(D1_INCOMPLETE_DEBT_ITEM_COUNT + D1_BLOCKED_DEBT_ITEM_COUNT);
    expect(EOS_PRODUCT_SECURITY_RELEASE_DEBT_COUNT).toBe(3);
    expect(D1K_STATUS).toBe("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D1K_REOPEN_REQUIRED).toBe(false);
    expect(D1L_STATUS).toBe("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D1L_REOPEN_REQUIRED).toBe(false);
    expect(D1N_STATUS).toBe("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D1N_REOPEN_REQUIRED).toBe(false);
    expect(D1_QUALIFIED_HUMAN_REVIEW_STATUS).toBe("INCOMPLETE");
    expect(D1_STRUCTURAL_ENGINEER_REVIEW_WORKFLOW_STATUS).toBe("INCOMPLETE");
    expect(D1_SOLVER_VALIDATION_STATUS).toBe("BLOCKED");
    expect(D1_ANALYTICAL_BENCHMARK_STATUS).toBe("INCOMPLETE");
    expect(D1_REFERENCE_SOLVER_COMPARISON_STATUS).toBe("INCOMPLETE");
    expect(D1_METHOD_CONFORMANCE_STATUS).toBe("INCOMPLETE");
    expect(D1_VALIDATION_EVIDENCE_MATRIX_STATUS).toBe("INCOMPLETE");
    expect(D1_PARAMETER_SEMANTICS_STATUS).toBe("COMPLETE_WITH_LIMITATIONS");
    expect(D1_STANDARDS_JURISDICTION_STATUS).toBe("COMPLETE_WITH_LIMITATIONS");
    expect(D1_INTERNAL_INTEGRATION_STATUS).toBe("INCOMPLETE");
    expect(D1_TO_D9_SOURCE_CONTRACT_STATUS).toBe("NOT_REQUIRED");
    expect(D1_UNSUPPORTED_CLAIM_DEBT_STATUS).toBe("COMPLETE_WITH_LIMITATIONS");
    expect(D1_REQUIRED_MANUAL_HUMAN_ACTION_COUNT).toBe(2);
    expect(D1_REQUIRED_EXTERNAL_EVIDENCE_COUNT).toBe(3);
    expect(D1_CLOSEOUT_TARGET).toBe("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D1_CLOSEOUT_CRITERIA).toContain("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D9_TRACK_COMPLETE).toBe(true);
    expect(D9_STATUS).toBe("COMPLETE_BOUNDED_WITH_LIMITATIONS");
    expect(D9_REOPENED).toBe(false);
    expect(EOS_ALL_DISCIPLINES_COMPLETE || EOS_GA_READY).toBe(false);
    expect(DATABASE_SCHEMA_CHANGED || NEW_DEPENDENCY_ADDED).toBe(false);
    expect(D1_READY_FOR_NEXT_PHASE).toBe(true);
    expect(D1_CANONICAL_NEXT_PHASE).toBe("EOS-D1G-VALIDATION-ROUTE-CANONICALIZATION");
    expect(D1_CANONICAL_NEXT_PHASE_TYPE).toBe("D1G_VALIDATION_ROUTE_CANONICALIZATION");
    expect(D1_CANONICAL_NEXT_PHASE_SCOPE).toContain("NOT_DEFINED");
    expect(D1_REMAINING_PHASES[2]?.dependencies).toContain("EOS-D1G-VALIDATION-ROUTE-CANONICALIZATION");
    const sourceText = readFileSync(join(here, "d1-structural-debt-canonicalization.ts"), "utf8");
    expect(sourceText).not.toMatch(/createHash|from ["']@rtb\/engineering-review["']|CREATE TABLE|eval\(|child_process|new Function/);
    expect(scanAnalysisFormulaBypass(join(here, "d1-structural-debt-canonicalization.ts"), sourceText)).toEqual([]);
  });
});
