    expect(decisions.DESIGN_MATURITY_STAGE_EQUALS_ENGINEERING_APPROVAL).toBe(false);
    expect(decisions.DESIGN_MATURITY_STAGE_EQUALS_CERTIFICATION).toBe(false);
    expect(decisions.D1N_STAGE_TRANSITION_GOVERNANCE_DEFINED).toBe(true);
    expect(decisions.D1N_ISSUES_GATE_DECISION).toBe(false);
    expect(decisions.D1N_AI_MAY_APPROVE_TRANSITION).toBe(false);
    expect(decisions.D1N_OWNERSHIP_ORCHESTRATION_MATRIX_DEFINED).toBe(true);
    expect(decisions.D1N_OWNED_CAPABILITIES).toContain("ORCHESTRATION_STATE");
    expect(decisions.D1N_ORCHESTRATED_CAPABILITIES).toContain("D1M_CURRENT_HANDOFF_INCLUSION");
    expect(decisions.D1N_CONSUMED_CAPABILITIES).toContain("D1A_IDENTITY");
    expect(decisions.D1N_EXTERNAL_AUTHORITY_CAPABILITIES).toEqual(expect.arrayContaining(["D1L_CERTIFICATION_GOVERNANCE", "LIFECYCLE_GATE_DECISION"]));
    expect(decisions.D1N_OUT_OF_SCOPE_CAPABILITIES).toContain("D9_MULTIDISCIPLINARY_REASONING");
    expect(decisions.D1N_ABSORBS_D1M).toBe(false);
    expect(decisions.D1N_ABSORBS_D1K).toBe(false);
    expect(decisions.D1N_ABSORBS_D1L).toBe(false);
    expect(decisions.D1N_ABSORBS_D9).toBe(false);
    expect(decisions.D1M_TO_D1N_HANDOFF_CONTRACT_REUSED).toBe(true);
    expect(decisions.D1N_INPUT_CONTRACT_DEFINED).toBe(true);
    expect(decisions.D1N_INPUT_CATEGORIES).toContain("D1M_CURRENT_HANDOFF");
    expect(decisions.D1N_OUTPUT_CONTRACT_DEFINED).toBe(true);
    expect(decisions.D1N_OUTPUT_CATEGORIES).toContain("STAGE_TRANSITION_REQUEST");
