    expect(decisions.D1N_PREREQUISITE_MATRIX.find((row) => row.area === "D9")?.status).toBe("FUTURE_DEPENDENCY");
    expect(decisions.D1N_AUTHORITY_MODEL_DEFINED).toBe(true);
    expect(decisions.D1N_HUMAN_GATES).toContain("DESIGN_PROGRESSION_ADVANCEMENT");
    expect(decisions.D1N_HUMAN_REVIEW_RUNTIME_COMPLETE).toBe(false);
    expect(decisions.AI_EQUALS_D1N_ENGINEERING_AUTHORITY).toBe(false);
    expect(decisions.ADMIN_EQUALS_D1N_ENGINEERING_AUTHORITY).toBe(false);
    expect(decisions.D1N_CURRENTNESS_MODEL_DEFINED).toBe(true);
    expect(decisions.D1N_CREATES_PARALLEL_CURRENTNESS_ENGINE).toBe(false);
    expect(decisions.D1N_CREATES_PARALLEL_LIFECYCLE_ENGINE).toBe(false);
    expect(decisions.D1N_DIGITAL_THREAD_BOUNDARY_DEFINED).toBe(true);
    expect(decisions.CANONICAL_DIGITAL_THREAD_REUSED).toBe(true);
    expect(decisions.PARALLEL_D1N_DIGITAL_THREAD_CREATED).toBe(false);
    expect(decisions.D1N_FOUNDATIONS_D1K_INTERNAL_INTEGRATION_READY).toBe(false);
    expect(decisions.D1N_FOUNDATIONS_D1K_INTELLIGENCE_READY).toBe(false);
