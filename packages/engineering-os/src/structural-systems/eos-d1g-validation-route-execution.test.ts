      "D1G.R1.EXTERNAL_SOLVER_ADAPTER_FOUNDATION",
      "D1G.R2.EXTERNAL_RESULT_PACKAGE_INGESTION",
      "D1G.R4.SPACE_GASS_MEMBER_STATION_FORCE_IMPORT",
      "D1G.R4.SPACE_GASS_SUPPORT_REACTION_FORCE_IMPORT",
