    expect(D1G_TECHNICAL_PASS_COUNT + D1G_TECHNICAL_FAIL_COUNT + D1G_TECHNICAL_BLOCKED_COUNT + D1G_TECHNICAL_NOT_APPLICABLE_COUNT).toBe(D1G_TECHNICAL_CASE_COUNT);
